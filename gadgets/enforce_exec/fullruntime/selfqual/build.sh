#!/bin/sh
# Builds the embedded artifacts of the D4 self-qualification prototype (and
# the E1 option C additions): the PT_INTERP fixture, the static probe helper
# (and its pinned sha256) and the D4 reference engine object. The option C
# engine objects are built by optcengine/build.sh.
set -eu
cd "$(dirname "$0")"
PH=/e1-interp-placeholder-xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx
gcc -nostdlib -fPIE -pie -O2 -fno-stack-protector -fcf-protection=none -Wl,--dynamic-linker=$PH \
	-Wl,-z,noexecstack -o helper/dyn helper/dyn.c
strip helper/dyn
(cd helper && xxd -i -n dyn_elf dyn > dyn_elf.h)
gcc -nostdlib -static-pie -fPIE -O1 -fno-stack-protector -fcf-protection=none -fno-builtin \
	-Wl,-z,noexecstack -Wl,-z,norelro -o helper/setexe helper/setexe.c
(cd helper && xxd -i -n setexe_elf setexe > setexe_elf.h)
gcc -static -O2 -Wall -pthread -o helper/probe-amd64 helper/probe.c
strip helper/probe-amd64
sum=$(sha256sum helper/probe-amd64 | cut -d' ' -f1)
cat > helper_sum_amd64.go <<GO
// Code generated by build.sh; DO NOT EDIT.

package selfqual

// helperSHA256 pins the embedded probe helper (helper/probe-amd64).
const helperSHA256 = "$sum"
GO
clang -target bpf -O2 -g -D__TARGET_ARCH_x86 -I ../../../../include/gadget/amd64 \
	-c refengine/bpf/refengine.bpf.c -o refengine/refengine_bpfel.o
llvm-strip -g refengine/refengine_bpfel.o
sha256sum helper/probe-amd64 refengine/refengine_bpfel.o
